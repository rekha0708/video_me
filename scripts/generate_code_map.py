"""Generate the code map under docs/code_map/ from the project source via AST.

The map is the project's "knowledge graph as flat files": per-package API
listings, the capability->adapter mapping, module dependency edges, Pydantic
model fields, dashboard routes, and env vars. Output is deterministic so
tests/test_code_map.py can assert docs/code_map/ is in sync with the code.

Regenerate with:  python -m scripts.generate_code_map
"""

from __future__ import annotations

import ast
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_DIR = REPO_ROOT / "docs" / "code_map"

# Packages whose classes/functions are documented in detail.
DETAIL_PACKAGES = ("core", "adapters", "services", "scripts")
# Extra directories listed in INDEX.md (one line per file) but not detailed.
INDEX_ONLY_PACKAGES = ("tests",)
# Curated files inside the output dir that the generator must never touch.
CURATED_FILES = {"LIMITATIONS.md"}

HEADER = "<!-- AUTO-GENERATED by scripts/generate_code_map.py — do not edit. Regenerate: python -m scripts.generate_code_map -->\n"


@dataclass
class FunctionInfo:
    name: str
    signature: str
    doc: str
    is_async: bool


@dataclass
class ClassInfo:
    name: str
    bases: list[str]
    doc: str
    methods: list[FunctionInfo]
    fields: list[tuple[str, str, str]]  # (name, annotation, default)


@dataclass
class ModuleInfo:
    path: Path  # relative to repo root
    doc: str
    classes: list[ClassInfo] = field(default_factory=list)
    functions: list[FunctionInfo] = field(default_factory=list)
    project_imports: list[str] = field(default_factory=list)

    @property
    def dotted(self) -> str:
        parts = self.path.with_suffix("").parts
        if parts[-1] == "__init__":
            parts = parts[:-1]
        return ".".join(parts)


def first_doc_line(node: ast.AST) -> str:
    doc = ast.get_docstring(node)  # type: ignore[arg-type]
    if not doc:
        return ""
    return doc.strip().splitlines()[0].strip()


def format_signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"({args}){returns}"


def collect_functions(body: list[ast.stmt]) -> list[FunctionInfo]:
    out: list[FunctionInfo] = []
    for node in body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append(
                FunctionInfo(
                    name=node.name,
                    signature=format_signature(node),
                    doc=first_doc_line(node),
                    is_async=isinstance(node, ast.AsyncFunctionDef),
                )
            )
    return out


def collect_class(node: ast.ClassDef) -> ClassInfo:
    fields: list[tuple[str, str, str]] = []
    for stmt in node.body:
        if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            default = ast.unparse(stmt.value) if stmt.value is not None else ""
            fields.append((stmt.target.id, ast.unparse(stmt.annotation), default))
        elif isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(
            stmt.targets[0], ast.Name
        ):
            # Unannotated class attrs (e.g. `name = "fetch_media"` on capability ABCs).
            fields.append((stmt.targets[0].id, "", ast.unparse(stmt.value)))
    return ClassInfo(
        name=node.name,
        bases=[ast.unparse(base) for base in node.bases],
        doc=first_doc_line(node),
        methods=collect_functions(node.body),
        fields=fields,
    )


def project_import_targets(node: ast.stmt) -> list[str]:
    roots = tuple(DETAIL_PACKAGES)
    targets: list[str] = []
    if isinstance(node, ast.Import):
        targets = [alias.name for alias in node.names]
    elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
        targets = [node.module]
    return [t for t in targets if t.split(".")[0] in roots]


def parse_module(path: Path) -> ModuleInfo | None:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError:
        return None
    info = ModuleInfo(path=path.relative_to(REPO_ROOT), doc=first_doc_line(tree))
    info.functions = collect_functions(tree.body)
    info.classes = [collect_class(n) for n in tree.body if isinstance(n, ast.ClassDef)]
    imports: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            imports.update(project_import_targets(node))
    info.project_imports = sorted(imports)
    return info


def iter_python_files(package: str) -> list[Path]:
    root = REPO_ROOT / package
    if not root.exists():
        return []
    return sorted(
        p
        for p in root.rglob("*.py")
        if "__pycache__" not in p.parts and ".venv" not in p.parts
    )


